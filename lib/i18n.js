const dicts = { en, sv };

export function dict(lang) {
	return dicts[lang] || en;
}

/** "3 hours ago" / "för 3 timmar sedan" */
export function ago(date, lang, now = Date.now()) {
	if (!date) return "";
	const s = Math.round((new Date(date).getTime() - now) / 1000);
	const rtf = new Intl.RelativeTimeFormat(lang === "sv" ? "sv" : "en", { numeric: "auto" });
	const steps = [[60, "second"], [3600, "minute"], [86400, "hour"], [604800, "day"], [2629800, "week"], [31557600, "month"], [Infinity, "year"]];
	const div = { second: 1, minute: 60, hour: 3600, day: 86400, week: 604800, month: 2629800, year: 31557600 };
	for (const [limit, unit] of steps) {
		if (Math.abs(s) < limit) return rtf.format(Math.round(s / div[unit]), unit);
	}
	return "";
}

export function formatDate(date, lang, opts = { day: "numeric", month: "short", year: "numeric" }) {
	if (!date) return "";
	return new Intl.DateTimeFormat(lang === "sv" ? "sv-SE" : "en-GB", { ...opts, timeZone: "Europe/Stockholm" }).format(new Date(date));
}
